// Generates internal/i18n/formats_gen.go and internal/i18n/testdata/plurals.json
// from the Intl data of Node.js (the same ICU/CLDR data WebView2 uses), so the
// CLI (Go) formats numbers, sizes and plural forms exactly like the window.
//
// Run: node tools/gen_formats.js   (then gofmt is not needed: output is formatted)
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const goSrc = fs.readFileSync(path.join(root, 'internal/i18n/i18n.go'), 'utf8');
const langs = [...goSrc.matchAll(/\{"([a-z]{2})", "[^"]+", "([^"]+)", (?:true|false)\}/g)].map(m => [m[1], m[2]]);
if (langs.length !== 30) throw new Error(`expected 30 languages in i18n.go, found ${langs.length}`);

const units = ['byte', 'kilobyte', 'megabyte', 'gigabyte', 'terabyte', 'second', 'minute', 'hour'];
const numberTypes = new Set(['integer', 'group', 'decimal', 'fraction']);

function pattern(parts) {
  let out = '', inNumber = false;
  for (const p of parts) {
    if (numberTypes.has(p.type)) {
      if (!inNumber) out += '{n}';
      inNumber = true;
    } else {
      out += p.value;
      inNumber = false;
    }
  }
  return out;
}

const lines = [];
const plurals = {};
for (const [code, tag] of langs) {
  const locale = tag.includes('-u-') ? tag : `${tag}-u-nu-latn`;
  const nf = new Intl.NumberFormat(locale);
  const parts = new Intl.NumberFormat(locale, { useGrouping: true }).formatToParts(12345.5);
  const decimal = parts.find(p => p.type === 'decimal').value;
  const group = (parts.find(p => p.type === 'group') || { value: '' }).value;
  const minGroup = nf.format(1234).length === 4 ? 2 : 1;
  const unitPatterns = {};
  for (const unit of units) {
    const value = unit === 'byte' || ['second', 'minute', 'hour'].includes(unit) ? 5 : 1.5;
    unitPatterns[unit] = pattern(new Intl.NumberFormat(locale, { style: 'unit', unit, unitDisplay: 'short' }).formatToParts(value));
    if (unit !== 'second' && unit !== 'minute' && unit !== 'hour') {
      unitPatterns[unit + '-per-second'] = pattern(new Intl.NumberFormat(locale, { style: 'unit', unit: unit + '-per-second', unitDisplay: 'short' }).formatToParts(value));
    }
  }
  const percent = pattern(new Intl.NumberFormat(locale, { style: 'percent', maximumFractionDigits: 1 }).formatToParts(0.455));
  const u = Object.entries(unitPatterns).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(', ');
  lines.push(`\t${JSON.stringify(code)}: {decimal: ${JSON.stringify(decimal)}, group: ${JSON.stringify(group)}, minGroup: ${minGroup}, percent: ${JSON.stringify(percent)}, units: map[string]string{${u}}},`);

  const rules = new Intl.PluralRules(tag.replace('-u-nu-latn', ''));
  const samples = {};
  for (const n of [...Array(231).keys(), 1000, 1001, 1002, 1005, 1011, 1021, 1000000, 2000000, 1.5]) samples[n] = rules.select(n);
  plurals[code] = samples;
}

const go = `// Code generated by tools/gen_formats.js from Intl (CLDR) data; DO NOT EDIT.

package i18n

// numberFormats are the separators and unit patterns of each language with
// Latin digits ("{n}" is the number).
var numberFormats = map[string]numberFormat{
${lines.join('\n')}
}
`;
fs.writeFileSync(path.join(root, 'internal/i18n/formats_gen.go'), go);
fs.writeFileSync(path.join(root, 'internal/i18n/testdata/plurals.json'), JSON.stringify(plurals, null, 1) + '\n');
console.log(`formats_gen.go and plurals.json written for ${langs.length} languages (node ${process.version})`);
