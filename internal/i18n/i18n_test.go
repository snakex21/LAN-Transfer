func TestNormalize(t *testing.T) {
	cases := map[string]string{
		"de-AT": "de", "pt_BR": "pt", "nb-NO": "no", "nn": "no", "zh-Hans-CN": "zh", "en_US.UTF-8": "en",
		"iw": "he", "AR-sa": "ar", "xx": "", "": "", "C": "",
	}
	for in, want := range cases {
		if got := Normalize(in); got != want {
			t.Errorf("Normalize(%q) = %q, want %q", in, got, want)
		}
	}
	if got := FromPreferred([]string{"gsw-CH", "fr-CH", "de-DE"}); got != "fr" {
		t.Errorf("FromPreferred = %q, want fr", got)
	}
	if got := FromPreferred([]string{"xx"}); got != Fallback {
		t.Errorf("FromPreferred unsupported = %q", got)
	}
}

// The Go plural rules must agree with Intl.PluralRules (testdata/plurals.json
// is generated by tools/gen_formats.js), so the CLI and the window choose
// the same forms.
func TestPluralRulesMatchIntl(t *testing.T) {
	data, err := os.ReadFile("testdata/plurals.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixture map[string]map[string]string
	if err := json.Unmarshal(data, &fixture); err != nil {
		t.Fatal(err)
	}
	if len(fixture) != len(Languages) {
		t.Fatalf("fixture has %d languages, want %d", len(fixture), len(Languages))
	}
	for lang, samples := range fixture {
		allowed := map[string]bool{}
		for _, c := range PluralCategories(lang) {
			allowed[c] = true
		}
		for n, want := range samples {
			value, _ := strconv.ParseFloat(n, 64)
			if got := PluralCategory(lang, value); got != want {
				t.Errorf("%s: PluralCategory(%s) = %s, Intl says %s", lang, n, got, want)
			}
			if value == float64(int64(value)) && !allowed[want] {
				t.Errorf("%s: category %s for %s is missing from PluralCategories", lang, want, n)
			}
		}
	}
}

func TestRender(t *testing.T) {
	if got := T("pl", "pick.selectedCount", "count", 3); got != "Wybrano 3 elementy" {
		t.Errorf("pl few: %q", got)
	}
	if got := T("pl", "pick.selectedCount", "count", 5); got != "Wybrano 5 elementów" {
		t.Errorf("pl many: %q", got)
	}
	if got := T("en", "pick.selectedCount", "count", 1); got != "1 item selected" {
		t.Errorf("en one: %q", got)
	}
	if got := T("en", "no.such.key"); got != "no.such.key" {
		t.Errorf("missing key: %q", got)
	}
	if got := T("en", "err.notEnoughSpace", "need", int64(3<<30), "free", int64(1536<<20)); got != "not enough space on the receiver's disk (needed 3 GB, free 1.5 GB)" {
		t.Errorf("sizes: %q", got)
	}
	if got := T("de", "err.notEnoughSpace", "need", int64(3<<30), "free", int64(1536<<20)); got == "" || !contains(got, "1,5 GB") {
		t.Errorf("de sizes: %q", got)
	}
	// Nested messages render in the same language.
	inner := New("err.wrongCode")
	if got := Render("en", Wrap(inner, "err.withPath", "path", "a.txt", "error", inner).Message()); got != "a.txt: wrong pairing code" {
		t.Errorf("nested: %q", got)
	}
	// A message decoded from JSON (remote error) keeps working.
	var m Msg
	raw, _ := json.Marshal(M("err.withPath", "path", "x", "error", New("err.diskFull")))
	if err := json.Unmarshal(raw, &m); err != nil {
		t.Fatal(err)
	}
	if got := Render("en", m); got != "x: the receiver's disk is full" {
		t.Errorf("decoded: %q", got)
	}
	if got := Render("en", Text("raw text")); got != "raw text" {
		t.Errorf("text: %q", got)
	}
}

func TestErrorsKeepIdentityAndMessage(t *testing.T) {
	sentinel := New("err.unsafeName")
	err := Wrap(sentinel, "err.name.reserved", "name", "CON")
	wrapped := fmt.Errorf("outer: %w", err)
	if !errors.Is(wrapped, sentinel) {
		t.Fatal("errors.Is lost the sentinel")
	}
	if m := MsgOf(wrapped); m.Key != "err.name.reserved" || m.Params["name"] != "CON" {
		t.Fatalf("MsgOf: %+v", m)
	}
	if m := MsgOf(errors.New("plain")); m.Key != "" || m.Params["text"] != "plain" {
		t.Fatalf("plain: %+v", m)
	}
	SetCurrent("en")
	defer SetCurrent(Fallback)
	if err.Error() != "unsafe file name: “CON” is a reserved Windows device name" {
		t.Fatalf("Error(): %q", err.Error())
	}
}

func TestFormats(t *testing.T) {
	cases := []struct{ lang, got, want string }{
		{"en", FormatSize("en", 0), "0 byte"},
		{"en", FormatSize("en", 1536), "1.5 kB"},
		{"en", FormatSize("en", 20<<20), "20 MB"},
		{"pl", FormatSize("pl", 1536), "1,5 kB"},
		{"fr", FormatSize("fr", 3<<20), "3 Mo"},
		{"ru", FormatSpeed("ru", 1.5*(1<<20)), "1,5 МБ/c"},
		{"de", FormatNumber("de", 1234567.25, 2), "1.234.567,25"},
		{"pl", FormatNumber("pl", 1234, 0), "1234"},
		{"pl", FormatNumber("pl", 12345, 0), "12\u00a0345"},
		{"tr", FormatPercent("tr", 45.5), "%45,5"},
		{"en", FormatDuration("en", 125), "2 min 5 sec"},
		{"en", FormatSpeed("en", 0), "—"},
	}
	for _, c := range cases {
		if c.got != c.want {
			t.Errorf("%s: got %q, want %q", c.lang, c.got, c.want)
		}
	}
}

func contains(s, sub string) bool {
	return len(sub) == 0 || (len(s) >= len(sub) && (s[:len(sub)] == sub || contains(s[1:], sub)))
}
